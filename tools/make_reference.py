"""Write the command reference (docs/reference.md) from the command table and the property
registry: every command, where it goes, its body and options, and every formatting property.

The tables in redocx.commands.builtin and redocx.props.registry are the definition of
the language, so the reference is complete by construction; tests/test_reference.py
checks that the committed file is up to date.

    python tools/make_reference.py            # rewrite docs/reference.md
    python tools/make_reference.py --check    # fail if it is out of date
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

from redocx.commands.builtin import CODE_BLOCK, COMMANDS
from redocx.commands.spec import CommandSpec
from redocx.explain import CATEGORIES, TARGETS, body, planned, sentence, value, where
from redocx.props.registry import REGISTRY

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "docs" / "reference.md"

INTRO = """\
# Command reference

<!-- Generated by tools/make_reference.py from the command table; do not edit. -->

Every command of redocx, with where it may appear, what its body holds and every option,
followed by every formatting property. To learn the language, start with the
[guide](guide/README.md); this page is for looking things up. The same facts are a command away:
`redocx explain table`, `redocx explain space-before`.

**Reading the entries.** A command is written `\\name[options]{body}`. Options are `name=value`,
separated by commas; an option that is on or off may be written alone (`[keep-with-next]` is
`keep-with-next=on`). Where an entry names a *positional* option, its value may be written without
the name: `\\list[Legal]` is `\\list[numbering=Legal]`. A value written `(a=..., b=...)` is a
group: `margins=(top=2cm, left=3cm)`; where the group has a main field, a single value is enough
(`margins=2.5cm`). Lengths take `pt`, `cm`, `mm`, `in` or `pc`; colours are `#RRGGBB`, a name or
`theme.accent1`. *Text* is a word, a `"string"` or `{plain text}`.

**Placement.** *A block of its own* means the command stands alone, between blank lines. *Inside
text* means it goes in a paragraph. Commands for parts (`\\row`, `\\cell`) go only directly inside
their parent.

**Not commands.** The short forms (`= Heading`, `1.` lists, pipe tables, `*strong*`, `_emphasis_`,
`@label`, `$$` display math, code fences, `%` comments) and the definitions `\\define` and `\\let`
are described in the [syntax guide](guide/syntax.md) and the [macro guide](guide/macros.md).
"""


def _cell(text: str) -> str:
    """Text for a Markdown table cell ("text" for the usual text value: see the intro)."""
    return value(text).replace("|", "\\|").replace("\n", " ")


def _anchor(name: str) -> str:
    return "cmd-" + name.replace(" ", "-")


def _command(spec: CommandSpec) -> list[str]:
    title = spec.title.capitalize() if spec.title else f"`\\{spec.name}`"
    lines = [f'<a id="{_anchor(spec.name)}"></a>', f"### {title}", "", sentence(spec.doc), ""]
    if (when := planned(spec)) is not None:
        lines += [f"*Not implemented ({when}): ignored with a warning.*", ""]
        return lines
    facts = [f"- **Where:** {where(spec)}.", f"- **Body:** {body(spec)}."]
    if spec.positional:
        many = " (several values: each one)" if spec.variadic else ""
        facts.append(f"- **Positional option:** `{spec.positional}`{many}.")
    if spec.props is not None:
        label, _ = TARGETS[spec.props]
        link = label.lower().replace(" ", "-")
        facts.append(f"- **Also takes** every one of the [{label.lower()}](#{link}) as an option.")
    if spec.patterns:
        for prefix, kind in spec.patterns.items():
            facts.append(f"- **Also takes** `{prefix}NAME=value`: {_cell(kind.describe())}.")
    lines += [*facts, ""]
    if spec.options:
        lines += ["| Option | Value | Meaning |", "|--------|-------|---------|"]
        for option in spec.options:
            name = f"`{option.name}`" + (" (required)" if option.required else "")
            later = spec.planned_options.get(option.name)
            meaning = option.doc + (f" *(planned for {later})*" if later else "")
            lines.append(f"| {name} | {_cell(option.type.describe())} | {_cell(meaning)} |")
        lines.append("")
    return lines


def _properties() -> list[str]:
    lines = [
        "## Formatting properties",
        "",
        "Formatting is set with properties: as options of the commands that take them, and as",
        "declarations in style sheets (`space-after: 6pt;`). The `ooxml.*` properties are escape",
        "hatches: raw WordprocessingML, checked against the schemas.",
        "",
    ]
    for target, (label, used) in TARGETS.items():
        lines += [f"### {label}", "", f"Used in {used}.", "", "| Property | Values | Meaning |"]
        lines.append("|----------|--------|---------|")
        for name, spec in REGISTRY[target].items():
            lines.append(f"| `{name}` | {_cell(spec.values)} | {_cell(spec.doc)} |")
        lines.append("")
    return lines


def render() -> str:
    lines = [INTRO, "## Commands by topic", ""]
    for category, names in CATEGORIES.items():
        links = ", ".join(f"[`\\{n}`](#{_anchor(n)})" for n in names)
        lines.append(f"- **{category}:** {links}")
    lines += [
        "",
        f"Code blocks take options too: see [code blocks](#{_anchor(CODE_BLOCK.name)}).",
        "",
    ]
    for category, names in CATEGORIES.items():
        lines += [f"## {category}", ""]
        for name in names:
            lines += _command(COMMANDS[name])
    lines += ["## Code blocks", ""]
    lines += _command(CODE_BLOCK)
    lines += _properties()
    return "\n".join(lines).rstrip() + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Write docs/reference.md from the command table.")
    parser.add_argument("--check", action="store_true", help="fail if docs/reference.md is stale")
    args = parser.parse_args(argv)
    text = render()
    if args.check:
        current = OUTPUT.read_text("utf-8") if OUTPUT.exists() else ""
        if current != text:
            print(f"{OUTPUT} is out of date: run python tools/make_reference.py", file=sys.stderr)
            return 1
        return 0
    OUTPUT.write_bytes(text.encode("utf-8"))
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
